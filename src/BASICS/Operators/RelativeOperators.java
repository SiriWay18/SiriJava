package BASICS.Operators;

public class RelativeOperators {
    public RelativeOperators(int a, int b) {
        System.out.println("RelativeOperators");
        System.out.println("a==b --> a equals b - " + (a==b) );
        System.out.println("a!=b --> a not equals b  - " + (a!=b) );
        System.out.println("a<b --> a lesser than  b   - " + (a<b) );
        System.out.println("a>b --> a greater than  b   - " + (a>b) );
        System.out.println("a<=b --> a lesser than or equals to b  -  " + (a<=b) );
        System.out.println("a>=b --> a greater than or equals to  b -  " + (a>=b) );
    }
}
